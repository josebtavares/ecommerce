export const nomeConcelho = (codigo) => CONCELHOS_CV.find(c => c.codigo === codigo)?.nome || ''

// tem o que o pagamento com cartão pede (igual a pagamentos.servico.tem_cidade no backend)
export function localizacaoCompleta (v) {
  if (!v) return false
  if ((v.cidade || '').trim()) return true
  return (v.pais || 'CV') === 'CV' && CONCELHOS_CV.some(c => c.codigo === v.concelho)
}

// { pais, concelho, cidade, codigo_postal } de um utilizador (perfil / localStorage)
export const localizacaoDe = (u) => ({
  pais: u?.pais || 'CV', concelho: u?.concelho || '', cidade: u?.cidade || '', codigo_postal: u?.codigo_postal || '',
})
